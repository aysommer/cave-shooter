export const GLYPH_W = 3;
export const GLYPH_H = 5;
export const LINE_H = GLYPH_H + 2;
const ADVANCE = GLYPH_W + 1;

export function measureText(str) {
  let max = 0;
  for (const line of String(str).split("\n")) max = Math.max(max, line.length);
  return { w: max > 0 ? max * ADVANCE - 1 : 0, h: String(str).split("\n").length * LINE_H - 2 };
}

export function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  let cx = x;
  let cy = y;
  for (const ch of String(str).toUpperCase()) {
    if (ch === "\n") {
      cx = x;
      cy += LINE_H;
      continue;
    }
    const g = G[ch] ?? G["?"];
    for (let i = 0; i < 15; i++) {
      if (g.charCodeAt(i) === 49) ctx.fillRect(cx + (i % 3), cy + ((i / 3) | 0), 1, 1);
    }
    cx += ADVANCE;
  }
}
